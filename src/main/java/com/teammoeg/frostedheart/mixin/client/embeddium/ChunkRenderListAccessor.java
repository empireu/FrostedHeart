package com.teammoeg.frostedheart.mixin.client.embeddium;

import me.jellysquid.mods.sodium.client.render.chunk.lists.ChunkRenderList;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.gen.Accessor;

/**
 * Exposes the backing section index array of a ChunkRenderList so WeatherFogRenderer can scan visible translucent
 * sections without allocating a ByteIterator.
 */
@Mixin(value = ChunkRenderList.class, remap = false)
public interface ChunkRenderListAccessor {
    @Accessor("sectionsWithGeometry")
    byte[] frostedheart$getSectionsWithGeometry();
}
